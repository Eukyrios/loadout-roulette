export const AMMO_BY_CALIBER: Record<string, Ammo[]> = AMMO.reduce(
  (acc, a) => {
    (acc[a.caliber] ??= []).push(a);
    return acc;
  },
  {} as Record<string, Ammo[]>,
);

// Hardest-hitting round first, so a board reads high-to-low around the rim.
for (const list of Object.values(AMMO_BY_CALIBER)) {
  list.sort((a, b) => (b.pen ?? -1) - (a.pen ?? -1));
}

/** Every round the given weapon can chamber. Empty if it fires no cartridge. */
export function ammoForWeapon(weaponId: string): Ammo[] {
  const cal = WEAPON_CALIBER[weaponId];
  return cal ? (AMMO_BY_CALIBER[cal] ?? []) : [];
}

/**
 * Where to look for a round's picture, best first — the same three-source
 * walk the attachment cards use, and for the same reason: the mirror is the
 * only one nothing can refuse, the raw CDN file can be hotlink-blocked, and
 * the site's own image optimiser usually is not.
 */
export const ammoImageSources = (a: Ammo): string[] =>
  a.img
    ? [
        `ammo/${a.id}.png`,
        a.img,
        `https://deltaforcetools.gg/_next/image?url=${encodeURIComponent(a.img)}&w=384&q=75`,
      ]
    : [];
